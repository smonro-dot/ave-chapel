export function allPatronages(): string[] {
  const set = new Set<string>();
  for (const s of SAINTS) for (const p of s.patronages) set.add(p);
  return [...set].sort((a, b) => a.localeCompare(b));
}

export function allTopics(): string[] {
  const set = new Set<string>();
  for (const s of SAINTS) for (const t of s.topics) set.add(t);
  return [...set].sort((a, b) => a.localeCompare(b));
}

export function saintBySlug(slug: string) {
  return SAINTS.find((s) => s.slug === slug);
}

